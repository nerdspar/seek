/**
 * Generates migrate-anime.sql from the reviewed anime-list.txt.
 *
 * Generates only — it never connects to a database and never runs anything.
 * Read the SQL before executing it, and take a backup first.
 *
 * Why one UPDATE per show is enough: a show, its seasons and its episodes are
 * all rows in app_item sharing the same (source, media_id), distinguished by
 * media_type plus season_number/episode_number. Floppy's own _child_bucket rule
 * is that children follow the show's bucket, so all of them move together.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const listPath = new URL('../anime-list.txt', import.meta.url);
const entries = readFileSync(listPath, 'utf8')
	.split('\n')
	.map((l) => l.trim())
	.filter((l) => l && !l.startsWith('#'))
	.map((l) => {
		const [id, ...rest] = l.split('\t');
		const [source, media_id] = id.split(':');
		return { source, media_id, title: (rest.join(' ') || '').trim() };
	})
	.filter((e) => e.source && e.media_id);

if (!entries.length) {
	console.error('No entries in anime-list.txt — nothing to generate.');
	process.exit(1);
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const pairs = entries.map((e) => `(${q(e.source)}, ${q(e.media_id)})`).join(',\n    ');

const sql = `-- Move ${entries.length} shows into the anime library bucket.
-- Generated by scripts/anime-migration-sql.mjs from anime-list.txt.
--
-- BEFORE RUNNING:
--   1. Back up the Floppy database.
--   2. Stop the Floppy container.
--   3. Set Preferences -> anime_library_mode to "both", or grouped anime will
--      appear in NEITHER the TV list nor the Anime list. This is verified
--      behaviour, not a guess.
--
-- Works on SQLite and PostgreSQL as written.

BEGIN;

-- 1. PRE-FLIGHT: must return 0 rows. Any row here is an existing anime-bucket
--    item that would collide with the update, since every app_item uniqueness
--    constraint includes library_media_type.
SELECT source, media_id, media_type, season_number, episode_number
FROM app_item
WHERE library_media_type = 'anime'
  AND (source, media_id) IN (
    ${pairs}
  );

-- 2. BEFORE: record what is about to change.
SELECT library_media_type, media_type, COUNT(*) AS rows
FROM app_item
WHERE (source, media_id) IN (
    ${pairs}
  )
GROUP BY library_media_type, media_type
ORDER BY media_type;

-- 3. THE CHANGE. Covers the show plus its season and episode rows, which share
--    (source, media_id).
UPDATE app_item
SET library_media_type = 'anime'
WHERE (source, media_id) IN (
    ${pairs}
  );

-- 4. AFTER: every row above should now read 'anime'.
SELECT library_media_type, media_type, COUNT(*) AS rows
FROM app_item
WHERE (source, media_id) IN (
    ${pairs}
  )
GROUP BY library_media_type, media_type
ORDER BY media_type;

-- 5. Nothing else should have moved. Expect 0.
SELECT COUNT(*) AS unexpected_anime_rows
FROM app_item
WHERE library_media_type = 'anime'
  AND (source, media_id) NOT IN (
    ${pairs}
  );

-- Inspect the results above. COMMIT only if steps 1 and 5 returned 0 and step 4
-- looks right. Otherwise ROLLBACK.
-- COMMIT;
ROLLBACK;
`;

writeFileSync(new URL('../migrate-anime.sql', import.meta.url), sql);
console.log(`migrate-anime.sql written for ${entries.length} shows:`);
for (const e of entries) console.log(`  ${e.source}:${e.media_id}  ${e.title}`);
console.log('\nThe file ends in ROLLBACK. Change it to COMMIT once the checks look right.');
console.log('Nothing was executed and no database was contacted.');
